/**
 * One-time generator for api/_birdcast-conus-mask.js.
 *
 * BirdCast's raster fills its whole bounding rectangle: far from any radar
 * (the open Pacific, deep Mexico/Canada) the values are interpolation relaxing
 * to a constant, not observations. BirdCast's own map clips hard at the U.S.
 * shoreline — but birds cross the Great Lakes and fly offshore, and coastal
 * radars do see them. Josh's call (2026-09-21): keep the contiguous U.S.
 * expanded by BUFFER_MILES in every direction. (A radar-range rule was tried
 * first — lumpy, and too tight along the coasts.) The renderer feathers the
 * edge (`scalar.feather`), so the mask itself stays a plain yes/no.
 *
 * Outline: us-atlas@3 `nation-10m.json` (U.S. Census Bureau cartographic
 * boundaries, ISC-licensed packaging by M. Bostock). A cell is kept when its
 * centre or any of four near-centre points falls inside the outline, so
 * coastal cells that are partly land survive.
 *
 *   node scripts/bake-birdcast/make-conus-mask.mjs
 */

import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { BIRDCAST_LAT, BIRDCAST_LON } from '../../api/_birdcast-core.js'

const SRC = 'https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/nation-10m.json'
const topo = await (await fetch(SRC)).json()
const { scale, translate } = topo.transform

// TopoJSON arcs are delta-encoded, quantized positions.
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]] })
})
const ringOf = (idxs) => {
  const pts = []
  for (const i of idxs) {
    const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse()
    pts.push(...(pts.length ? a.slice(1) : a))
  }
  return pts
}
const rings = topo.objects.nation.geometries[0].arcs.flatMap((poly) => poly.map(ringOf))
  // Only rings that can touch the output box (drops Alaska, Hawaii, territories).
  .filter((r) => r.some(([x, y]) => x > -126 && x < -66 && y > 24 && y < 50))

// Even-odd rule across every ring (holes included).
const inside = (lng, lat) => {
  let hit = false
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i], [xj, yj] = r[j]
      if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
    }
  }
  return hit
}

const BUFFER_MILES = 100
const BUFFER_KM = BUFFER_MILES * 1.609344
const RAD = Math.PI / 180
// Distance (km) from a point to the nearest outline segment, in a local
// equirectangular frame around the point — exact enough at 100-mile scale.
const segs = rings.flatMap((r) => r.map((p, i) => [p, r[(i + 1) % r.length]]))
const nearOutline = (lng, lat) => {
  const kx = 111.32 * Math.cos(lat * RAD), ky = 110.57
  const dLat = BUFFER_KM / ky + 0.3, dLng = BUFFER_KM / kx + 0.3
  for (const [[x1, y1], [x2, y2]] of segs) {
    if (Math.min(y1, y2) > lat + dLat || Math.max(y1, y2) < lat - dLat || Math.min(x1, x2) > lng + dLng || Math.max(x1, x2) < lng - dLng) continue
    const ax = (x1 - lng) * kx, ay = (y1 - lat) * ky, bx = (x2 - lng) * kx, by = (y2 - lat) * ky
    const dx = bx - ax, dy = by - ay
    const t = Math.max(0, Math.min(1, -(ax * dx + ay * dy) / (dx * dx + dy * dy || 1)))
    if (Math.hypot(ax + t * dx, ay + t * dy) <= BUFFER_KM) return true
  }
  return false
}

const nLat = BIRDCAST_LAT.length
const nLon = BIRDCAST_LON.length
const bits = new Uint8Array(Math.ceil((nLat * nLon) / 8))
const OFF = [[0, 0], [-0.08, -0.08], [0.08, -0.08], [-0.08, 0.08], [0.08, 0.08]]
let kept = 0
for (let r = 0; r < nLat; r++) {
  for (let c = 0; c < nLon; c++) {
    const lng = BIRDCAST_LON[c] - 360
    if (!OFF.some(([dx, dy]) => inside(lng + dx, BIRDCAST_LAT[r] + dy)) && !nearOutline(lng, BIRDCAST_LAT[r])) continue
    const i = r * nLon + c
    bits[i >> 3] |= 1 << (i & 7)
    kept++
  }
}

const out = `// GENERATED by scripts/bake-birdcast/make-conus-mask.mjs - do not edit.
// Coverage mask (contiguous U.S. expanded by ${BUFFER_MILES} miles) on the BirdCast bake grid (${nLat} x ${nLon}, row-major from
// lat0, bit i = cell i, LSB first). ${kept} of ${nLat * nLon} cells kept.
// Outline: us-atlas@3.0.1 nation-10m (U.S. Census Bureau cartographic boundaries).
export const CONUS_MASK_DIMS = [${nLat}, ${nLon}]
export const CONUS_MASK_B64 = '${Buffer.from(bits).toString('base64')}'
`
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'api', '_birdcast-conus-mask.js'), out)
console.log(`make-conus-mask: kept ${kept}/${nLat * nLon} cells`)

// Eyeball check (north up).
for (let r = nLat - 1; r >= 0; r -= 3) {
  let line = ''
  for (let c = 0; c < nLon; c += 2) { const i = r * nLon + c; line += (bits[i >> 3] >> (i & 7)) & 1 ? '#' : '.' }
  console.log(line)
}

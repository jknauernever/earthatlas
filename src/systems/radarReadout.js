const TILE = 256

/**
 * @param tileUrl  the radar tile template on screen ({z}/{x}/{y})
 * @returns {Promise<{ dry: true } | { lo: number, hi: number|null } | null>}
 *   null = could not read (network, decode) — the caller says so.
 */
export async function readRadarAt(tileUrl, lng, lat, z) {
  const n = 2 ** z
  const fx = ((lng + 180) / 360) * n
  const s = Math.sin((lat * Math.PI) / 180)
  const fy = (0.5 - Math.log((1 + s) / (1 - s)) / (4 * Math.PI)) * n
  const tx = Math.floor(fx), ty = Math.floor(fy)
  const px = Math.min(TILE - 1, Math.floor((fx - tx) * TILE))
  const py = Math.min(TILE - 1, Math.floor((fy - ty) * TILE))
  try {
    const r = await fetch(tileUrl.replace('{z}', z).replace('{x}', tx).replace('{y}', ty))
    if (r.status === 204 || r.status === 404) return { dry: true } // no tile = no rain anywhere in it
    if (!r.ok) return null
    const bmp = await createImageBitmap(await r.blob())
    const c = new OffscreenCanvas(1, 1)
    const ctx = c.getContext('2d')
    ctx.drawImage(bmp, px, py, 1, 1, 0, 0, 1, 1)
    const [R, G, B, A] = ctx.getImageData(0, 0, 1, 1).data
    if (A < 8) return { dry: true }
    let best = null, bd = Infinity
    for (const row of RADAR_RAMP) {
      const d = (row[2] - R) ** 2 + (row[3] - G) ** 2 + (row[4] - B) ** 2
      if (d < bd) { bd = d; best = row }
    }
    return bd > 300 ? null : { lo: best[0], hi: best[1] } // not a ramp colour: do not guess
  } catch { return null }
}
